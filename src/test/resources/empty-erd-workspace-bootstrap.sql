CREATE TABLE public.unit (
 unit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 unit_code VARCHAR(50) NOT NULL UNIQUE, unit_name VARCHAR(100) NOT NULL
);
CREATE TABLE public.farm (
 farm_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farm_name VARCHAR(150) NOT NULL, address VARCHAR(255) NOT NULL,
 area_ha NUMERIC(10,2) NOT NULL, description VARCHAR(1000),
 status VARCHAR(10) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.plot (
 plot_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farm_id INTEGER NOT NULL REFERENCES public.farm,
 plot_name VARCHAR(150) NOT NULL, area_ha NUMERIC(10,2) NOT NULL,
 soil_type VARCHAR(100), location VARCHAR(255), description VARCHAR(1000),
 status VARCHAR(10) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.crop (
 crop_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 crop_name VARCHAR(100) NOT NULL, scientific_name VARCHAR(150),
 category VARCHAR(100), growth_days INTEGER, description VARCHAR(1000),
 status VARCHAR(10) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.crop_season (
 season_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 plot_id INTEGER NOT NULL REFERENCES public.plot, crop_id INTEGER NOT NULL REFERENCES public.crop,
 yield_unit_id INTEGER NOT NULL REFERENCES public.unit, season_name VARCHAR(100) NOT NULL,
 planned_start_date DATE NOT NULL, planned_end_date DATE NOT NULL,
 actual_start_date DATE, actual_end_date DATE, expected_yield NUMERIC(15,3),
 status VARCHAR(20) NOT NULL CHECK(status IN ('PLANNED','IN_PROGRESS','COMPLETED','CANCELLED')),
 record_status VARCHAR(10) NOT NULL CHECK(record_status IN ('ACTIVE','VOID')),
 description VARCHAR(1000), created_by INTEGER NOT NULL REFERENCES public.app_user,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(planned_end_date>=planned_start_date)
);
CREATE TABLE public.farm_member (
 farm_id INTEGER NOT NULL REFERENCES public.farm, user_id INTEGER NOT NULL REFERENCES public.app_user,
 status VARCHAR(10) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 joined_at TIMESTAMPTZ NOT NULL, PRIMARY KEY(farm_id,user_id)
);
CREATE TABLE public.farm_member_role (
 farm_id INTEGER NOT NULL, user_id INTEGER NOT NULL, role_id INTEGER NOT NULL REFERENCES public.role,
 PRIMARY KEY(farm_id,user_id,role_id), FOREIGN KEY(farm_id,user_id) REFERENCES public.farm_member
);
CREATE TABLE public.material (
 material_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 unit_id INTEGER NOT NULL REFERENCES public.unit, material_name VARCHAR(150) NOT NULL,
 category VARCHAR(100), description VARCHAR(1000),
 status VARCHAR(10) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.warehouse (
 warehouse_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 farm_id INTEGER NOT NULL REFERENCES public.farm, warehouse_name VARCHAR(100) NOT NULL,
 location VARCHAR(255), description VARCHAR(1000),
 status VARCHAR(10) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.inventory (
 inventory_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 warehouse_id INTEGER NOT NULL REFERENCES public.warehouse,
 material_id INTEGER NOT NULL REFERENCES public.material,
 reorder_level NUMERIC(15,3) NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.inventory_transaction (
 transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inventory_id INTEGER NOT NULL REFERENCES public.inventory,
 transaction_type VARCHAR(20) NOT NULL, reason_code VARCHAR(30) NOT NULL,
 quantity NUMERIC(15,3) NOT NULL, po_item_id INTEGER, task_id INTEGER,
 reverses_transaction_id BIGINT REFERENCES public.inventory_transaction,
 note VARCHAR(1000) NOT NULL, occurred_at TIMESTAMPTZ NOT NULL,
 record_status VARCHAR(10) NOT NULL, created_by INTEGER NOT NULL REFERENCES public.app_user,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE public.low_stock_alert (
 alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inventory_id INTEGER NOT NULL REFERENCES public.inventory,
 opened_at TIMESTAMPTZ NOT NULL, resolved_at TIMESTAMPTZ
);
